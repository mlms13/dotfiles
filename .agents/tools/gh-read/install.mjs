import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { userInfo } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const source = dirname(fileURLToPath(import.meta.url));
const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;

export function install(home = userInfo().homedir, node = process.execPath, agents = ["codex", "claude"]) {
  if (agents.some((agent) => !["codex", "claude"].includes(agent))) {
    throw new Error("Usage: node install.mjs [codex|claude] (default: both)");
  }
  const launcher = join(home, ".agents/bin/gh-read");
  const script = join(home, ".agents/lib/gh-read/gh-read.mjs");
  const allowlist = join(home, ".agents/gh-read-repos.json");
  mkdirSync(dirname(launcher), { recursive: true });
  mkdirSync(dirname(script), { recursive: true });
  copyFileSync(join(source, "gh-read.mjs"), script);
  // Clear Node preload options before Node starts, and pin the installed runtime.
  writeFileSync(launcher, `#!/bin/sh\nexec /usr/bin/env -i HOME=${quote(home)} PATH=/usr/bin:/bin ${quote(node)} ${quote(script)} "$@"\n`, { mode: 0o755 });
  if (!existsSync(allowlist)) {
    const previous = join(home, ".codex/gh-read/repos.json");
    copyFileSync(existsSync(previous) ? previous : join(source, "repos.example.json"), allowlist);
  }
  if (agents.includes("codex")) {
    const rules = join(home, ".codex/rules/gh-read.rules");
    mkdirSync(dirname(rules), { recursive: true });
    writeFileSync(rules, `# Generated by ~/.agents/tools/gh-read/install.mjs\nprefix_rule(pattern=[${JSON.stringify(launcher)}], decision="allow", justification="Read GitHub data through the shared wrapper and repository allowlist.")\n`);
  }
  if (agents.includes("claude")) {
    const path = join(home, ".claude/settings.json");
    const settings = existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : {};
    settings.permissions ??= {};
    settings.permissions.allow ??= [];
    const rule = `Bash(${launcher} *)`;
    if (!settings.permissions.allow.includes(rule)) settings.permissions.allow.push(rule);
    settings.permissions.ask ??= [];
    for (const pattern of ["Edit(~/.agents/bin/gh-read)", "Edit(~/.agents/lib/gh-read/**)", "Edit(~/.agents/gh-read-repos.json)"]) {
      if (!settings.permissions.ask.includes(pattern)) settings.permissions.ask.push(pattern);
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, `${JSON.stringify(settings, null, 2)}\n`);
  }
  return launcher;
}

if (import.meta.main) {
  try {
    const agents = process.argv.slice(2);
    if (agents.length > 1) throw new Error("Usage: node install.mjs [codex|claude] (default: both)");
    const launcher = install(userInfo().homedir, process.execPath, agents.length ? agents : undefined);
    console.log(`Installed ${launcher}. Repository allowlist preserved. Restart the selected agents to reload permissions.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
